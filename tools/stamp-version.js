/* Writes app/version.js from package.json so every build (desktop, Android, iOS, web) knows its own version.
   Called by tools/build.js and tools/build-web.js; run it by hand with: node tools/stamp-version.js */
const fs = require('fs'); const path = require('path');
const root = path.join(__dirname, '..');
const v = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
fs.writeFileSync(path.join(root, 'app', 'version.js'), "/* generated by tools/stamp-version.js */\n(window.BP = window.BP || {}).appVersion = '" + v + "';\n");
