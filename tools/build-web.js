/* Builds the browser / phone version of Blockpad into site/app/  (the same app code as the desktop app):
     node tools/build-web.js
   - adapts index.html (manifest, theme colour, iOS home-screen tags, a CSP that lets your own AI endpoint be reached)
   - adds a service worker so the app loads offline after the first visit, plus icons
   The result is a normal PWA (installable on Android, iOS, Windows, macOS, Linux) and also the web assets for the Android app. */
const fs = require('fs'); const path = require('path'); const crypto = require('crypto');
const root = path.join(__dirname, '..');
const src = path.join(root, 'app');
const out = path.join(root, 'site', 'app');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

require('./stamp-version');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const walk = (d, base = '') => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name), base + e.name + '/') : [base + e.name]));
const files = walk(src);
files.forEach((f) => {
  const to = path.join(out, f); fs.mkdirSync(path.dirname(to), { recursive: true });
  let data = fs.readFileSync(path.join(src, f));
  if (/\.(js|html)$/.test(f)) data = Buffer.from(data.toString('utf8').replace(/\.\.\/assets\//g, 'assets/'));
  fs.writeFileSync(to, data);
});
// assets the page references
fs.mkdirSync(path.join(out, 'assets'), { recursive: true });
fs.copyFileSync(path.join(root, 'assets', 'logo.svg'), path.join(out, 'assets', 'logo.svg'));
['icon-192.png', 'icon-512.png', 'maskable-512.png', 'apple-touch-180.png'].forEach((f) => fs.copyFileSync(path.join(root, 'assets', 'icons', f), path.join(out, 'assets', f)));

// optional relay (TURN) servers shipped with the web/phone app: put turn.json ([{urls, username, credential}]) in the project root
if (fs.existsSync(path.join(root, 'turn.json'))) fs.copyFileSync(path.join(root, 'turn.json'), path.join(out, 'turn.json'));

// index.html for the web
let html = fs.readFileSync(path.join(out, 'index.html'), 'utf8');
const csp = "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https: http:; media-src 'self' data: blob: https: http:; frame-src 'self' blob: data: https: http:; object-src 'self' blob: data:; font-src 'self' data:; connect-src 'self' blob: data: https: http: wss:; manifest-src 'self'; worker-src 'self'";
html = html.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/, `<meta http-equiv="Content-Security-Policy" content="${csp}">`)
  .replace('<meta name="viewport" content="width=device-width, initial-scale=1">', '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n  <meta name="theme-color" content="#5b5bd6">\n  <meta name="mobile-web-app-capable" content="yes">\n  <meta name="apple-mobile-web-app-capable" content="yes">\n  <meta name="apple-mobile-web-app-status-bar-style" content="default">\n  <meta name="apple-mobile-web-app-title" content="Blockpad">\n  <link rel="manifest" href="manifest.webmanifest">\n  <link rel="apple-touch-icon" href="assets/apple-touch-180.png">')
  .replace('</body>', '  <script src="pwa.js"></script>\n</body>');
fs.writeFileSync(path.join(out, 'index.html'), html);

fs.writeFileSync(path.join(out, 'manifest.webmanifest'), JSON.stringify({
  name: 'Blockpad', short_name: 'Blockpad', description: 'Notes, wiki and databases that live on your device.',
  start_url: './', scope: './', display: 'standalone', orientation: 'any', background_color: '#ffffff', theme_color: '#5b5bd6', categories: ['productivity', 'utilities'],
  icons: [
    { src: 'assets/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: 'assets/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: 'assets/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}, null, 2));

fs.writeFileSync(path.join(out, 'pwa.js'), `/* registers the offline cache (only over http/https; not in the Electron app) */
if ('serviceWorker' in navigator && /^https?:$/.test(location.protocol)) {
  const had = !!navigator.serviceWorker.controller;      // an update (not the first install) takes over: reload once so the new version runs
  let reloaded = false;
  navigator.serviceWorker.addEventListener('controllerchange', () => { if (had && !reloaded) { reloaded = true; location.reload(); } });
  window.addEventListener('load', () => navigator.serviceWorker.register('sw.js').then((r) => r.update()).catch(() => {}));
}
`);
const all = walk(out).filter((f) => f !== 'sw.js');
const hash = crypto.createHash('sha1'); all.sort().forEach((f) => { hash.update(f); hash.update(fs.readFileSync(path.join(out, f))); });
const version = pkg.version + '-' + hash.digest('hex').slice(0, 10);
fs.writeFileSync(path.join(out, 'sw.js'), `/* Blockpad offline cache. Generated by tools/build-web.js. */
const CACHE = 'blockpad-${version}';
const FILES = ${JSON.stringify(['./', ...all], null, 1)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('blockpad-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const r = e.request;
  if (r.method !== 'GET' || new URL(r.url).origin !== location.origin) return;       // your own AI endpoint and link previews are never cached
  e.respondWith(caches.match(r, { ignoreSearch: true }).then((hit) => hit || fetch(r).catch(() => (r.mode === 'navigate' ? caches.match('./index.html') : Response.error()))));
});
`);
console.log('web app built:', out, '|', all.length, 'files | cache', version);
