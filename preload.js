const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('bp', {
  load: () => ipcRenderer.invoke('ws:load'),
  save: (json) => ipcRenderer.invoke('ws:save', json),
  saveSync: (json) => ipcRenderer.sendSync('ws:saveSync', json),
  dataPath: () => ipcRenderer.invoke('ws:path'),
  reveal: () => ipcRenderer.invoke('ws:reveal'),
  chooseDir: () => ipcRenderer.invoke('ws:chooseDir'),
  setDir: (dir, useExisting) => ipcRenderer.invoke('ws:setDir', dir, !!useExisting),
  resetDir: () => ipcRenderer.invoke('ws:resetDir'),
  onExternal: (cb) => ipcRenderer.on('ws:external', () => cb()),
  saveFile: (name, content, isBase64) => ipcRenderer.invoke('file:save', name, content, !!isBase64),
  savePdf: (name) => ipcRenderer.invoke('pdf:save', name),
  exportFolder: (files) => ipcRenderer.invoke('export:folder', files),
  showItem: (p) => ipcRenderer.invoke('show:item', p),
  devtools: () => ipcRenderer.invoke('devtools'),
  fetchMeta: (url) => ipcRenderer.invoke('meta:fetch', url),
  aiChat: (req) => ipcRenderer.invoke('ai:chat', req),
  apiConfigure: (cfg) => ipcRenderer.invoke('api:configure', cfg),
  ready: () => ipcRenderer.invoke('app:ready'),
  onLink: (cb) => ipcRenderer.on('app:link', (_e, url) => cb(url)),
  zipApp: () => ipcRenderer.invoke('app:zip'),
  p2p: {
    join: (id, topic) => ipcRenderer.invoke('p2p:join', { id, topic }),
    leave: (id) => ipcRenderer.invoke('p2p:leave', { id }),
    send: (peer, data) => ipcRenderer.invoke('p2p:send', { peer, data }),
    status: () => ipcRenderer.invoke('p2p:status'),
    stop: () => ipcRenderer.invoke('p2p:stop'),
    onEvent: (cb) => ipcRenderer.on('p2p:event', (_e, ev) => cb(ev)),
  },
  llm: {
    status: () => ipcRenderer.invoke('llm:status'),
    start: (cfg) => ipcRenderer.invoke('llm:start', cfg),
    stop: () => ipcRenderer.invoke('llm:stop'),
    download: (id) => ipcRenderer.invoke('llm:download', id),
    cancel: () => ipcRenderer.invoke('llm:cancel'),
    remove: (id) => ipcRenderer.invoke('llm:remove', id),
    onEvent: (cb) => ipcRenderer.on('llm:event', (_e, st) => cb(st)),
  },
});
